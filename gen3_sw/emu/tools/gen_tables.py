"""Generate src/tables.h: the constant tables of the Node numerics, taken from the Python references so the C++
emulator uses exactly the same values (no libm in the emulator for these constants).

    python gen3_sw/emu/tools/gen_tables.py

Sources: tb/vru/reference_model/{silu,gelu}64_coefficients.json (PWL activations), tb/gen2/block_max_attention.py
(P thresholds, c_j table), tb/node/native_attention_numpy.py (reciprocal table), tb/gen2/g2lib.py (epsilon).
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(REPO / "tb" / "gen2"))
sys.path.insert(0, str(REPO / "tb" / "node"))
sys.path.insert(0, str(REPO / "tb" / "vru" / "reference_model" / "python"))

import g2lib  # noqa: E402
import gelu_pwl64  # noqa: E402
import silu_pwl64  # noqa: E402
from block_max_attention import C_TABLE, T_NORMAL, T_SUB  # noqa: E402
from native_attention_numpy import NativeAttention  # noqa: E402


def arr(name: str, ctype: str, values, per_line: int = 8, fmt=str) -> str:
    vals = [fmt(v) for v in values]
    lines = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n"


def main() -> None:
    hx = lambda v: f"0x{int(v):08X}u"  # noqa: E731
    na = NativeAttention(REPO)
    out = ["// Generated by gen3_sw/emu/tools/gen_tables.py from the Python references. Do not edit.",
           "#pragma once", "#include <cstdint>", "", "namespace g3 {", "namespace tables {", ""]
    out.append("// SiLU / GELU 64-segment PWL: {positive slope, negative slope, bias} as FP32 bits")
    out.append(arr("SILU", "uint32_t", [v for c in silu_pwl64.COEFFICIENTS for v in c], 6, hx))
    out.append(arr("GELU", "uint32_t", [v for c in gelu_pwl64.COEFFICIENTS for v in c], 6, hx))
    out.append("// block-max softmax: P code thresholds (16 fraction bits), c_j interpolation table")
    out.append(arr("T_NORMAL", "int64_t", [int(v) for v in T_NORMAL], 8, lambda v: f"{v}LL"))
    out.append(arr("T_SUB", "int64_t", [int(v) for v in T_SUB], 8, lambda v: f"{v}LL"))
    out.append(arr("C_TABLE", "int64_t", [int(v) for v in C_TABLE], 9, lambda v: f"{v}LL"))
    out.append("// reciprocal of l (Gen1 table): round(2^23 / (1 + i/32))")
    out.append(arr("RECIP_LUT", "int64_t", [int(v) for v in na.recip_lut], 6, lambda v: f"{v}LL"))
    out.append("// RMSNorm epsilon profiles (FP32 bits)")
    out.append(arr("EPSILON", "uint32_t", g2lib.EPSILON, 4, hx))
    out += ["}  // namespace tables", "}  // namespace g3", ""]
    dst = HERE.parent / "src" / "tables.h"
    dst.write_text("\n".join(out))
    print("wrote", dst)


if __name__ == "__main__":
    main()
